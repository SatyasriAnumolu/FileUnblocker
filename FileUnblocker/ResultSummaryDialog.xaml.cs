using System.Windows;
using System.Windows.Input;
using System.Windows.Media;
using System.Windows.Media.Animation;
using FileUnblocker.ViewModels;

namespace FileUnblocker;

public partial class ResultSummaryDialog : Window
{
    // ?? View model ????????????????????????????????????????????????????????
    private readonly ResultSummaryViewModel _vm;
    // Set to true in Closing so in-flight CompositionTarget ticks are no-ops.
    private bool _dialogClosing;

    // ?? Factory ???????????????????????????????????????????????????????????
    /// <summary>
  /// Creates and shows the dialog modally.
    /// Returns the user's choice: true = "View Results", false/null = "Done" / closed.
    /// </summary>
    public static bool? Show(Window owner, ResultSummaryViewModel vm)
    {
        var dlg = new ResultSummaryDialog(vm) { Owner = owner };
        return dlg.ShowDialog();
    }

    // ?? Constructor ???????????????????????????????????????????????????????
    public ResultSummaryDialog(ResultSummaryViewModel vm)
    {
        InitializeComponent();
    _vm = vm;
      Closing += (_, _) => _dialogClosing = true;
  Loaded  += (_, _) => Populate();
    }

    // ?? Populate UI from ViewModel ????????????????????????????????????????
    private void Populate()
    {
        // ?? Headline ??????????????????????????????????????????????????????
        TxtHeadline.Text       = _vm.Headline;
        TxtHeadline.Foreground = new SolidColorBrush(
     (Color)ColorConverter.ConvertFromString(_vm.HeadlineColour));

        // ?? Sub-headline (time + rate) ????????????????????????????????????
TxtSubHeadline.Text =
        $"Completed in {_vm.ElapsedDisplay}  ·  {_vm.SuccessRateDisplay} success rate";

   // ?? Stat row ??????????????????????????????????????????????????????
      TxtTotal.Text       = _vm.Total.ToString();
        TxtElapsed.Text     = _vm.ElapsedDisplay;
        TxtSuccessRate.Text = _vm.SuccessRateDisplay;

        // ?? Animate counters from 0 ? target ?????????????????????????????
        AnimateCounter(StatUnblocked, 0, _vm.Unblocked,    Color.FromRgb(0x10, 0xB9, 0x81));
        AnimateCounter(StatClear,     0, _vm.AlreadyClear, Color.FromRgb(0xC4, 0xB5, 0xFD));
        AnimateCounter(StatArchives,  0, _vm.ArchivesProcessed, Color.FromRgb(0xA7, 0x8B, 0xFA));
   AnimateCounter(StatFailed,    0, _vm.Failed,       Color.FromRgb(0xF8, 0x71, 0x71));

      // ?? Adapt hero icon + badge for failure state ?????????????????????
        if (_vm.HasFailures)
      {
IconPath.Data   = Geometry.Parse("M12,5 L12,13 M12,17 L12,17.5");
   IconPath.Stroke = new SolidColorBrush(Color.FromRgb(0xF8, 0x71, 0x71));
          BadgeGrad0.Color = Color.FromRgb(0x2D, 0x10, 0x10);
      BadgeGrad1.Color = Color.FromRgb(0x1E, 0x0A, 0x0A);
      BadgeShadow.Color = Color.FromRgb(0xF8, 0x71, 0x71);
      GlowStop.Color    = Color.FromArgb(0x30, 0xF8, 0x71, 0x71);
     }

   // ?? Hide Failed card if no errors ?????????????????????????????????
     StatFailedBorder.Opacity  = _vm.HasFailures ? 1 : 0.35;
        StatArchiveBorder.Opacity = _vm.HasArchives ? 1 : 0.35;

    // ?? Entrance animation ????????????????????????????????????????????
  Opacity = 0;
        var fade = new DoubleAnimation(0, 1, TimeSpan.FromMilliseconds(300))
        {
    EasingFunction = new CubicEase { EasingMode = EasingMode.EaseOut }
        };
        BeginAnimation(OpacityProperty, fade);

        // Slide up — applied to RootBorder, NOT to the Window.
      // WPF throws InvalidOperationException("Transform is not valid for Window")
        // when RenderTransform is set directly on a Window instance.
      var slideTransform = new TranslateTransform(0, 20);
        RootBorder.RenderTransform = slideTransform;
        var slide = new DoubleAnimation(20, 0, TimeSpan.FromMilliseconds(350))
    {
            EasingFunction = new CubicEase { EasingMode = EasingMode.EaseOut }
        };
      slideTransform.BeginAnimation(TranslateTransform.YProperty, slide);
    }

    // ?? Counter animation ?????????????????????????????????????????????????
    private void AnimateCounter(
  System.Windows.Controls.TextBlock tb, int from, int to, Color color)
    {
   tb.Foreground = new SolidColorBrush(color);
        if (to == 0) { tb.Text = "0"; return; }

      var start = DateTime.UtcNow;
        const double ms = 600;
        EventHandler? tick = null;
     tick = (_, _) =>
      {
  // Stop immediately if the dialog is closing — prevents touching
  // a partially-disposed visual tree and avoids COMException.
         if (_dialogClosing)
        {
    CompositionTarget.Rendering -= tick;
     return;
       }
           double t     = Math.Min((DateTime.UtcNow - start).TotalMilliseconds / ms, 1.0);
        double eased = 1 - Math.Pow(1 - t, 3);
    tb.Text = ((int)Math.Round(from + (to - from) * eased)).ToString();
            if (t >= 1.0) CompositionTarget.Rendering -= tick;
    };
 CompositionTarget.Rendering += tick;
    }

    // ?? Title bar drag ????????????????????????????????????????????????????
    private void TitleBar_MouseDown(object sender, MouseButtonEventArgs e)
    {
        if (e.LeftButton == MouseButtonState.Pressed) DragMove();
    }

    // ?? Button handlers ???????????????????????????????????????????????????
    private void BtnClose_Click(object sender, RoutedEventArgs e)    => Close();
    private void BtnDismiss_Click(object sender, RoutedEventArgs e)  => Close();
    private void BtnViewResults_Click(object sender, RoutedEventArgs e)
    {
        DialogResult = true;   // caller will apply a filter / bring main window to front
Close();
    }
}
